import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('administrator curates completed competition results with accessible validation and stale-write recovery', async ({ page, context }) => {
  test.setTimeout(180000);
  let fpcRequests = 0;
  context.on('request', request => { if (/^https:\/\/(www\.)?fpcanoagem\.pt\//.test(request.url())) fpcRequests++; });
  await page.goto('/login');
  await page.getByLabel('Correio eletrónico ou identificador CFC').fill('e2e-admin@example.test');
  await page.getByLabel('Palavra-passe').fill('correct horse 7');
  await page.getByRole('button', { name: 'Iniciar sessão' }).click();
  await expect(page).toHaveURL(/\/today$/);
  await page.goto('/admin/eventos/criar');
  const title = `Resultados FPC E2E ${Date.now()}`;
  await page.locator('#event-title').fill(title);
  await page.locator('#event-type').selectOption('COMPETITION');
  await page.locator('#event-starts-at').fill(new Date(Date.now() - 48 * 3600000).toISOString().slice(0, 16));
  await page.locator('#event-ends-at').fill(new Date(Date.now() - 47 * 3600000).toISOString().slice(0, 16));
  await page.getByRole('button', { name: 'Criar evento', exact: true }).click();
  while (await page.getByRole('link', { name: title, exact: true }).count() === 0) await page.getByRole('link', { name: 'Seguinte' }).click();
  await page.getByRole('link', { name: title, exact: true }).click();
  const detail = page.url();
  await expect(page.getByRole('link', { name: 'Editar evento', exact: true })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Resultados oficiais na FPC', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Gerir ligação de resultados' }).focus();
  await page.keyboard.press('Enter');
  await expect(page).toHaveURL(/\/resultados$/);
  const management = page.url();
  await page.setViewportSize({ width: 320, height: 800 });
  const input = page.getByLabel('Ligação para os resultados oficiais (opcional)');
  await input.fill('https://fpcanoagem.pt.evil.test/results.pdf');
  await page.getByRole('button', { name: 'Guardar ligação' }).click();
  await expect(input).toHaveValue('https://fpcanoagem.pt.evil.test/results.pdf');
  await expect(input).toHaveAttribute('aria-invalid', 'true');
  await expect(page.locator('.error-summary')).toBeFocused();
  if (process.env.E2E_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.E2E_SCREENSHOT_DIR}/event-results-mobile.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
  const axe = await new AxeBuilder({ page }).analyze();
  expect(axe.violations.filter(v => ['serious', 'critical'].includes(v.impact))).toEqual([]);
  await input.fill('https://fpcanoagem.pt/resultados/prova.pdf');
  await page.getByRole('button', { name: 'Guardar ligação' }).click();
  const link = page.getByRole('link', { name: 'Resultados oficiais na FPC', exact: true });
  await expect(link).toHaveAttribute('href', 'https://fpcanoagem.pt/resultados/prova.pdf');
  await expect(link).toHaveAttribute('referrerpolicy', 'no-referrer');
  await page.setViewportSize({ width: 1280, height: 900 });
  if (process.env.E2E_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.E2E_SCREENSHOT_DIR}/event-results-desktop.png`, fullPage: true });
  await page.goto('/events');
  await page.getByRole('link', { name: 'Eventos passados', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Eventos passados', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(page.getByRole('region', { name: 'Calendário de eventos' })).toHaveCount(0);
  for (let n = 0; n < 30 && await page.getByRole('link', { name: title, exact: true }).count() === 0; n++) {
    await page.getByRole('link', { name: 'Seguinte', exact: true }).click();
  }
  const pastListURL = page.url();
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
  expect((await new AxeBuilder({ page }).analyze()).violations.filter(v => ['serious', 'critical'].includes(v.impact))).toEqual([]);
  if (process.env.E2E_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.E2E_SCREENSHOT_DIR}/past-events-mobile.png`, fullPage: true });
  await page.getByRole('link', { name: title, exact: true }).click();
  await expect(page.getByRole('link', { name: 'Resultados oficiais na FPC', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Voltar aos eventos', exact: true }).click();
  // A first-page return may canonicalize the optional page number.
  expect(new URL(page.url()).searchParams.get('view')).toBe('past');
  expect(new URL(page.url()).searchParams.get('page') || '1').toBe(new URL(pastListURL).searchParams.get('page') || '1');
  await expect(page.getByRole('link', { name: title, exact: true })).toBeVisible();
  await page.goto(management);
  const stale = await context.newPage();
  await stale.goto(management);
  await page.getByLabel('Ligação para os resultados oficiais (opcional)').fill('https://www.fpcanoagem.pt/resultados/final.pdf');
  await page.getByRole('button', { name: 'Guardar ligação' }).click();
  await stale.getByLabel('Ligação para os resultados oficiais (opcional)').fill('');
  await stale.getByRole('button', { name: 'Guardar ligação' }).click();
  await expect(stale.getByRole('link', { name: 'Carregar a ligação atual' })).toBeVisible();
  await expect(stale.getByRole('alert')).toBeFocused();
  await stale.getByRole('link', { name: 'Carregar a ligação atual' }).click();
  await expect(stale.getByLabel('Ligação para os resultados oficiais (opcional)')).toHaveValue('https://www.fpcanoagem.pt/resultados/final.pdf');
  await stale.getByLabel('Ligação para os resultados oficiais (opcional)').fill('');
  await stale.getByRole('button', { name: 'Guardar ligação' }).click();
  await page.goto(detail);
  await expect(link).toHaveCount(0);
  expect(fpcRequests).toBe(0);
  await stale.close();
});
